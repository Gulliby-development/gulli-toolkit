test("the channel order: switch on, move up and down, the first that works wins", function()
    Fake({ channels = { 1, "General - Elwynn", false, 4, "ПоискСпутников", false } })
    local ns = Load()
    local order = ns.db.order
    ns.ToggleChannel(order, "SAY")
    eq(table.concat(order, ","), "RAID,PARTY")
    eq(ns.Say("hi"), false, "nothing works: alone and no say")
    eq(#W.chat, 0)
    assert(W.printed[1]:find("No channel"))
    ns.ToggleChannel(order, "LFG")
    ns.ToggleChannel(order, "GUILD")
    eq(ns.Say("hi"), "LFG", "LookingForGroup by its name in another language")
    eq(W.chat[1][2], "CHANNEL"); eq(W.chat[1][3], 4)
    assert(ns.MoveChannel(order, "GUILD", -1))
    eq(table.concat(order, ","), "RAID,PARTY,GUILD,LFG")
    eq(ns.MoveChannel(order, "RAID", -1), false, "the first stays first")
    eq(ns.MoveChannel(order, "LFG", 1), false, "the last stays last")
    W.guild, W.now = true, W.now + 5
    eq(ns.Say("hi"), "GUILD")
    eq(ns.CanUse("TRADE"), nil, "not in Trade outside a city")
    eq(ns.CanUse("GENERAL"), "CHANNEL")
    for _, k in ipairs(ns.CHANNELS) do assert(ns.L["CH_" .. k] ~= "CH_" .. k, k .. " has no name") end
end)

