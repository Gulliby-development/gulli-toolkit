test("default phrases follow the client language; own phrases join them", function()
    Fake({ locale = "ruRU" })
    local ns = Load()
    eq(ns.Phrases()[2], "Готов!")
    assert(ns.AddPhrase("  Сундук мой  "))
    eq(#ns.Phrases(), 11)
    eq(ns.Phrases()[11], "Сундук мой")
    eq(ns.AddPhrase("Сундук мой"), false, "a phrase is listed once")
    ns.RemovePhrase("Готов!")
    eq(ns.Phrases()[2], ns.L.P3, "the third default moved up")
    eq(ns.RingPlace("Готов!"), nil, "and it left the ring")
    eq(ns.AddPhrase("   "), false)
    ns.ResetPhrases()
    eq(#ns.Phrases(), 10)
    eq(ns.RingPlace("Готов!"), 2)
end)

