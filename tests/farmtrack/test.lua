end)

test("slash commands add items by link or id, gold with a goal in gold", function()
    Fake({})
    local ns = Load()
    ns.Slash("add |cffffffff|Hitem:4338::::::::20:::::|h[Mageweave Cloth]|h|r 60")
    eq(ns.Targets()[1].id, CLOTH)
    eq(ns.Targets()[1].goal, 60)
