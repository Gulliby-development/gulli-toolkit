    eq(k, "OTHER", "a weak word alone is no group"); eq(d, nil)
    k, d = kind("aq")
    eq(k, "OTHER")
    k, d = kind("WTB stock of linen")
    eq(k, "WTB"); eq(d, nil)
    k, d = kind("selling Scarlet Leggings")
    eq(d, nil, "an item name is not the Scarlet Monastery")
    k, d, r = kind("LFM ST need tank")
