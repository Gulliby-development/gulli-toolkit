-- Run from the repository root: lua5.1 tests/bulletin/test.lua
local W = dofile("tests/bulletin/wow.lua")
local test, eq = W.test, W.eq

local function kind(msg)
    Fake({})
    local ns = Load()
    return ns.Classify(msg)
end

test("groups: LFM and LFG with the dungeon", function()
    local k, d, r = kind("LF2M DM need tank and heal")
    eq(k, "GROUP"); eq(d, "DM"); eq(r, "LFM")
    k, d, r = kind("Priest LFG Scholo or Strat")
    eq(k, "GROUP"); eq(d, "SCHOLO"); eq(r, "LFG")
    k, d = kind("LFM SM:GY pst")
    eq(d, "SM", "SM:GY")
    k, d = kind("LF1M DME tribute run")
    eq(d, "DIREMAUL", "DM East is Dire Maul, not the Deadmines")
    k, d = kind("lfm [Zul'Farrak] 2 dps")
    eq(d, "ZF", "an apostrophe inside the name")
    k, d, r = kind("UBRS 8/10 need 2")
    eq(k, "GROUP"); eq(d, "UBRS"); eq(r, "LFM")
end)

test("a dungeon name alone is a group", function()
    local k, d, r = kind("BRD arena run anyone?")
    eq(k, "GROUP"); eq(d, "BRD"); eq(r, "LFM")
end)

test("selling, buying, crafting, guilds and other", function()
    eq(kind("WTS |cff1eff00|Hitem:7909::::::::|h[Aquamarine]|h|r 2g"), "WTS")
    eq(kind("WTB Large Brilliant Shard"), "WTB")
    eq(kind("LF enchanter for Crusader, have mats"), "CRAFT")
    eq(kind("<Forever Friends> recruiting all classes"), "GUILD")
    eq(kind("anyone know where the flight master is"), "OTHER")
    eq(kind("WTS DM summons"), "WTS", "selling wins over the dungeon")
end)

test("other languages", function()
    eq(kind("Продам Медную руду"), "WTS")
    eq(kind("куплю ткань"), "WTB")
    local k, d = kind("нужен танк в Мертвые копи")
    eq(k, "GROUP"); eq(d, "DM")
    eq(kind("ПРОДАМ РУДУ"), "WTS", "capital Cyrillic")
    eq(kind("Verkaufe Kupfererz"), "WTS")
    eq(kind("出售 铜矿"), "WTS")
end)

test("one poster keeps one message per kind, and messages expire", function()
    Fake({})
    local ns = Load()
    ns.Add("WTS Copper Ore", "Bob-Realm", "Trade")
    ns.Add("LFM RFC", "Bob-Realm", "LookingForGroup")
    ns.Add("WTS Tin Ore", "Bob-Realm", "Trade")
    eq(#ns.posts, 2)
    eq(ns.posts[1].text, "WTS Tin Ore")
    eq(ns.posts[1].short, "Bob")
    eq(ns.Count("WTS"), 1)
    W.now = W.now + 16 * 60
    ns.Add("WTB Linen", "Ann", "Trade")
    eq(#ns.View("WTS"), 0, "15 minutes later the old message is gone")
    eq(#ns.View("WTB"), 1)
end)

test("other chat is skipped unless switched on; secret values are skipped", function()
    Fake({})
    local ns = Load()
    eq(ns.Add("hello there", "Bob", "General"), nil)
    ns.db.other = true
    assert(ns.Add("hello there", "Bob", "General"))
    issecretvalue = function(v) return v == "secret" end
    eq(ns.Add("secret", "Ann", "Trade"), nil)
    eq(ns.Add("WTS ore", "secret", "Trade"), nil)
end)

test("the group view sorts by dungeon level, with a header for each and my level filter", function()
    Fake({ level = 20 })
    local ns = Load()
    ns.Add("LFM Strat", "A")
    ns.Add("LFM RFC", "B")
    ns.Add("LFM WC", "C")
    ns.Add("LFG anything", "D")
    local all = ns.View("GROUP", false, 20)
    eq(all[1].header, true); eq(all[1].dungeon, "RFC")
    eq(all[2].author, "B")
    eq(all[3].dungeon, "WC")
    eq(all[5].dungeon, "STRAT")
    eq(all[7].header, true); eq(all[7].dungeon, nil, "no dungeon goes last")
    local mine = ns.View("GROUP", true, 20)
    for _, x in ipairs(mine) do assert(x.dungeon ~= "STRAT", "Stratholme is not for level 20") end
end)

test("chat events reach the board, the window opens, whisper and invite", function()
    Fake({ areas = { [2437] = "Огненная пропасть" } })
    local ns = Load()
    W.Fire("CHAT_MSG_CHANNEL", "LFG RFC", "Bob-Realm", "", "", "", "", 0, 0, "LookingForGroup")
    eq(#ns.posts, 1)
    eq(ns.posts[1].channel, "LookingForGroup")
    eq(ns.DungeonName("RFC"), "Огненная пропасть", "the game's localized area name")
    eq(ns.DungeonName("UBRS"), "Upper Blackrock Spire")
    SlashCmdList.GULLIBULLETIN("")
    ns.Refresh()
    ns.Whisper("Bob-Realm")
    ns.Invite("Bob-Realm")
    eq(W.opened[1], "/w Bob-Realm ")
    eq(W.invited[1], "Bob-Realm")
    SlashCmdList.GULLIBULLETIN("clear")
    eq(#ns.posts, 0)
end)

