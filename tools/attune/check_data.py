"""Checks Gulli-Attune's chains against the QuestieDB Forever data.

    python3 tools/attune/check_data.py <questiedb-checkout>

1. Every step in ns.RAIDS (Gulli-Attune/Core.lua) must exist in the data under the same English name.
2. Lists quests that look like an attunement or that reward a key, that Core.lua does not track
   and that seen.txt does not list yet. A human (or the daily check) decides whether one becomes
   a new chain; --update-seen then adds the rest to seen.txt, so only new quests show up next time.
3. With --info, prints ns.INFO for Core.lua instead: per step its required level, where its
   starter stands on the zone map (x, y in percent, 0 when unknown) and the items it asks for.
Exits 1 when a step is missing or renamed.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "questcleaner"))
import questie  # noqa: E402

CORE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Gulli-Attune", "Core.lua")
Q_NAME, Q_STARTED_BY, Q_REQ_LEVEL, Q_OBJECTIVES = 1, 2, 4, 10
N_SPAWNS, N_ZONE = 7, 9
O_SPAWNS, O_ZONE = 4, 5
I_NAME, I_REWARD_OF = 1, 6
LOOKS_LIKE = re.compile(r"attune|\bkey\b|seal of|amulet|brooch|sewer|scepter|the dread citadel", re.I)
SEEN = os.path.join(os.path.dirname(os.path.abspath(__file__)), "seen.txt")


def read_seen():
    if not os.path.exists(SEEN):
        return set()
    return {int(line.split()[0]) for line in open(SEEN, encoding="utf-8") if line.strip() and line[0].isdigit()}


def tracked_steps(path):
    text = open(path, encoding="utf-8").read()
    steps = [(int(i), name) for i, name in re.findall(r'\{ (\d+), "((?:[^"\\]|\\.)*)"', text)]
    any_of = {int(i) for group in re.findall(r"anyOf = \{([^}]*)\}", text) for i in re.findall(r"\d+", group)}
    return steps, any_of


def seq(t):
    return [t[k] for k in sorted(t)] if isinstance(t, dict) else []


def step_areas(path):
    """Quest id -> the area id its step names (the starter's zone in the window)."""
    text = open(path, encoding="utf-8").read()
    names = {}
    for left, right in re.findall(r"^local ([A-Z_, ]+) = ([\d, ]+)$", text, re.M):
        for n, v in zip(left.split(","), right.split(",")):
            names[n.strip()] = int(v)
    out = {}
    for qid, area in re.findall(r'\{ (\d+), "(?:[^"\\]|\\.)*", "(?:[^"\\]|\\.)*", (\w+)', text):
        out[int(qid)] = int(area) if area.isdigit() else names.get(area)
    return out


def spot(rec, spawns_key, zone_key, prefer=None):
    spawns = rec.get(spawns_key) or {}
    # The spawn in the zone the step names, when the starter stands in several zones.
    zone = prefer if prefer in spawns else rec.get(zone_key)
    pts = seq(spawns.get(zone) or {}) if zone in spawns else []
    if not pts:
        for z in sorted(spawns):
            pts = seq(spawns[z])
            if pts:
                break
    if pts:
        xy = seq(pts[0])
        if len(xy) >= 2 and xy[0] >= 0 and xy[1] >= 0:
            return xy[0], xy[1]
    return 0, 0


def info(root):
    # With the Forever corrections, where every quest Forever added lives.
    quests, npcs, objects, _ = questie.load_forever(root)
    steps, any_of = tracked_steps(CORE)
    areas = step_areas(CORE)
    print("-- Generated by tools/attune/check_data.py --info: quest -> { level, x, y, items asked for (id, count) }.")
    print("ns.INFO = {")
    for qid in sorted({i for i, _ in steps} | any_of):
        q = quests.get(qid) or {}
        x = y = 0
        sb = q.get(Q_STARTED_BY) or {}
        for nid in seq(sb.get(1) or {}):
            x, y = spot(npcs.get(nid) or {}, N_SPAWNS, N_ZONE, areas.get(qid))
            break
        else:
            for oid in seq(sb.get(2) or {}):
                x, y = spot(objects.get(oid) or {}, O_SPAWNS, O_ZONE, areas.get(qid))
                break
        need = []
        for o in seq((q.get(Q_OBJECTIVES) or {}).get(3) or {}):
            need += [o.get(1), o.get(2) or 1]
        fx = lambda v: ("%.1f" % v).rstrip("0").rstrip(".") if v else "0"
        print("    [%d] = { %d, %s, %s, { %s } }," % (qid, q.get(Q_REQ_LEVEL) or 0, fx(x), fx(y),
                                               ", ".join(str(v) for v in need)))
    print("}")
    return 0


def main(root, update_seen=False):
    quests, _, _, items = questie.load_forever(root)
    steps, any_of = tracked_steps(CORE)
    known = {i for i, _ in steps} | any_of
    seen = read_seen()
    new = []
    bad = 0
    for qid, name in steps:
        got = quests.get(qid, {}).get(Q_NAME)
        if got != name.replace("\\'", "'"):
            print(f"STEP {qid} {name!r}: data has {got!r}")
            bad += 1
    key_quests = set()
    for item in items.values():
        if re.search(r"\bkey\b|seal|amulet|brooch|scepter", item.get(I_NAME) or "", re.I):
            key_quests.update((item.get(I_REWARD_OF) or {}).values())
    for qid in sorted(quests):
        name = quests[qid].get(Q_NAME) or ""
        if qid in known or qid in seen:
            continue
        if qid in key_quests or LOOKS_LIKE.search(name):
            print(f"CANDIDATE {qid} {name}")
            new.append(f"{qid} {name}")
    if update_seen and new:
        with open(SEEN, "a", encoding="utf-8") as f:
            f.write("\n".join(new) + "\n")
    print(f"{len(steps)} steps checked, {bad} wrong")
    return 1 if bad else 0


if __name__ == "__main__":
    if "--info" in sys.argv[2:]:
        sys.exit(info(sys.argv[1]))
    sys.exit(main(sys.argv[1], "--update-seen" in sys.argv[2:]))
