"""Builds Gulli-AutoQuest/Drops.lua from the QuestieDB Forever data.

    python3 tools/autoquest/build_drops.py <questiedb-checkout>

For each quest with an item to collect, the mobs that drop that item, so the quest mob key and
button can look for them too. A quest's droppers are the ones that spawn in the quest's zone when
any do, at most MAX of them. Names stay English here; the addon asks the client for the name in
its own language by npc id. QuestieDB is GPLv3.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "questcleaner"))
import questie  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "Gulli-AutoQuest", "Drops.lua")
MAX = 5

# questKeys, npcKeys and itemKeys of QuestieDB (src/meta/*Meta.lua).
Q_OBJECTIVES, Q_ZONE, Q_SPECIAL = 10, 17, 24
N_NAME, N_SPAWNS = 1, 7
I_NPC_DROPS = 2


def seq(t):
    if isinstance(t, dict):
        return [t[k] for k in sorted(k for k in t if isinstance(k, int))]
    return list(t or [])


def lua_str(s):
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(root):
    quests, npcs, _, items = questie.load_forever(root)
    drops, names, areas = {}, {}, {}
    for qid, q in quests.items():
        if not isinstance(q, dict):
            continue
        # The areas where the quest's mobs (to kill, or that drop its items) spawn: a quest of
        # another zone's log header whose work is here (Tanaris' Super Sticky in Un'Goro).
        mobs = []
        ob = q.get(Q_OBJECTIVES)
        if isinstance(ob, dict):
            for c in seq(ob.get(1)):
                cid = c.get(1) if isinstance(c, dict) else c
                if isinstance(cid, int) and isinstance(npcs.get(cid), dict):
                    mobs.append(cid)
            for o in seq(ob.get(3)):
                it = items.get(o.get(1)) if isinstance(o, dict) else None
                if isinstance(it, dict):
                    mobs += [n for n in seq(it.get(I_NPC_DROPS)) if isinstance(npcs.get(n), dict)]
        found = []
        for n in mobs:
            for a in (npcs[n].get(N_SPAWNS) or {}):
                if isinstance(a, int) and a > 0 and a not in found:
                    found.append(a)
        if found:
            areas[qid] = sorted(found)
        objs = seq((q.get(Q_OBJECTIVES) or {}).get(3) if isinstance(q.get(Q_OBJECTIVES), dict) else None)
        if not objs:
            continue
        zone = q.get(Q_ZONE) if isinstance(q.get(Q_ZONE), int) and q.get(Q_ZONE) > 0 else None
        rows = []
        for o in objs:
            item = o.get(1) if isinstance(o, dict) else None
            it = items.get(item) if item else None
            ids = [n for n in seq(it.get(I_NPC_DROPS)) if isinstance(npcs.get(n), dict)] if isinstance(it, dict) else []
            if zone:
                here = [n for n in ids if zone in (npcs[n].get(N_SPAWNS) or {})]
                ids = here or ids
            ids = sorted(set(ids), key=ids.index)[:MAX]
            rows.append((item or 0, ids))
            for n in ids:
                names[n] = npcs[n].get(N_NAME)
        if any(ids for _, ids in rows):
            drops[qid] = rows
    lines = ["-- Generated by tools/autoquest/build_drops.py from QuestieDB (GPLv3). Do not edit by hand.",
             "-- ns.DROPS[quest] = { { item, npc, ... }, ... } in the order of the quest's items;",
             "-- ns.NPC_NAME[npc] = English name (the client gives its own by id);",
             "-- ns.QUEST_AREAS[quest] = the area ids where its mobs spawn.",
             "local _, ns = ...", "ns.DROPS = {"]
    for qid in sorted(drops):
        parts = ["{ %s }" % ", ".join(str(x) for x in [item] + ids) for item, ids in drops[qid]]
        lines.append("    [%d] = { %s }," % (qid, ", ".join(parts)))
    lines.append("}")
    lines.append("ns.NPC_NAME = {")
    for n in sorted(names):
        lines.append("    [%d] = %s," % (n, lua_str(names[n])))
    lines.append("}")
    lines.append("ns.QUEST_AREAS = {")
    for qid in sorted(areas):
        lines.append("    [%d] = { %s }," % (qid, ", ".join(str(a) for a in areas[qid])))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("quests", len(drops), "npcs", len(names), "areas", len(areas))


if __name__ == "__main__":
    main(sys.argv[1])
