"""Builds Gulli-AutoQuest/Drops.lua from the QuestieDB Forever data.

    python3 tools/autoquest/build_drops.py <questiedb-checkout>

The quest mob key and button look for the mobs a quest needs where the player is. The quest log
gives the objectives; this data adds what the log does not say: which mobs drop an item to collect
(ns.DROPS, every dropper, the ones of the quest's zone first), which mobs a kill objective counts
(ns.KILLS, for an objective named by a group text), and where each of those mobs spawns
(ns.NPC_AREAS, area ids), so a quest of another zone's log header counts where its mobs live and a
dropper of another zone is left out. Names stay English here; the addon asks the client for the
name in its own language by npc id. QuestieDB is GPLv3.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "questcleaner"))
import questie  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "Gulli-AutoQuest", "Drops.lua")
# An item a whole region drops (cloth, a common trade good) lists hundreds of mobs; past this many
# the item is no quest mob's.
MAX = 200

# questKeys, npcKeys and itemKeys of QuestieDB (src/meta/*Meta.lua).
Q_OBJECTIVES, Q_ZONE = 10, 17
N_NAME, N_SPAWNS = 1, 7
I_NPC_DROPS = 2


def seq(t):
    if isinstance(t, dict):
        return [t[k] for k in sorted(k for k in t if isinstance(k, int))]
    return list(t or [])


def lua_str(s):
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def areas_of(npc):
    return sorted(a for a in (npc.get(N_SPAWNS) or {}) if isinstance(a, int) and a > 0)


def main(root):
    quests, npcs, _, items = questie.load_forever(root)
    drops, kills, used = {}, {}, set()
    for qid, q in quests.items():
        if not isinstance(q, dict) or not isinstance(q.get(Q_OBJECTIVES), dict):
            continue
        ob = q[Q_OBJECTIVES]
        zone = q.get(Q_ZONE) if isinstance(q.get(Q_ZONE), int) and q.get(Q_ZONE) > 0 else None
        krows = []
        for c in seq(ob.get(1)):
            cid = c.get(1) if isinstance(c, dict) else c
            krows.append([cid] if isinstance(cid, int) and isinstance(npcs.get(cid), dict) else [])
        if any(krows):
            kills[qid] = krows
            for r in krows:
                used.update(r)
        rows = []
        for o in seq(ob.get(3)):
            item = o.get(1) if isinstance(o, dict) else None
            it = items.get(item) if item else None
            ids = [n for n in seq(it.get(I_NPC_DROPS)) if isinstance(npcs.get(n), dict)] if isinstance(it, dict) else []
            ids = sorted(set(ids), key=ids.index)
            if len(ids) > MAX:
                ids = []
            if zone:
                ids.sort(key=lambda n: 0 if zone in (npcs[n].get(N_SPAWNS) or {}) else 1)
            rows.append((item or 0, ids))
            used.update(ids)
        if any(ids for _, ids in rows):
            drops[qid] = rows
    lines = ["-- Generated by tools/autoquest/build_drops.py from QuestieDB (GPLv3). Do not edit by hand.",
             "-- ns.DROPS[quest] = { { item, npc, ... }, ... } in the order of the quest's items, the",
             "-- quest zone's droppers first; ns.KILLS[quest] = { { npc }, ... } in the order of its kill",
             "-- objectives; ns.NPC_NAME[npc] = English name (the client gives its own by id);",
             "-- ns.NPC_AREAS[npc] = the area ids where it spawns.",
             "local _, ns = ...", "ns.DROPS = {"]
    for qid in sorted(drops):
        parts = ["{ %s }" % ", ".join(str(x) for x in [item] + ids) for item, ids in drops[qid]]
        lines.append("    [%d] = { %s }," % (qid, ", ".join(parts)))
    lines.append("}")
    lines.append("ns.KILLS = {")
    for qid in sorted(kills):
        lines.append("    [%d] = { %s }," % (qid, ", ".join("{ %s }" % ", ".join(map(str, r)) for r in kills[qid])))
    lines.append("}")
    lines.append("ns.NPC_NAME = {")
    for n in sorted(used):
        lines.append("    [%d] = %s," % (n, lua_str(npcs[n].get(N_NAME))))
    lines.append("}")
    lines.append("ns.NPC_AREAS = {")
    for n in sorted(used):
        a = areas_of(npcs[n])
        if a:
            lines.append("    [%d] = { %s }," % (n, ", ".join(map(str, a))))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("drops", len(drops), "kills", len(kills), "npcs", len(used))


if __name__ == "__main__":
    main(sys.argv[1])
