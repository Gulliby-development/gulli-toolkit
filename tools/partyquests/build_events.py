"""Writes Events.lua of Party Quests and Auto Quest: the quests that tie up their NPC once one
player starts them (escorts, fights, scenes), from QuestieDB.

    python3 tools/partyquests/build_events.py <questiedb-checkout>

A Classic quest counts when it has the game's party-accept flag (questFlags 2: the others get
a "join this quest" prompt). WoW Forever's own quests carry no flags in the data, so for
them, and for any quest the flag misses, the objective text decides ("Escort ...", "Help ...
escape", "Protect ..."). Class quests are left out (nobody waits for them), and so is NOT.
Both modules get the same file, since they share no code at run time.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "questcleaner"))
import questie  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUTS = [os.path.join(ROOT, "Gulli-PartyQuests", "Events.lua"), os.path.join(ROOT, "Gulli-AutoQuest", "Events.lua")]

# questKeys of QuestieDB (src/meta/questMeta.lua).
Q_NAME, Q_CLASSES, Q_OBJ_TEXT, Q_TRIGGER, Q_FLAGS = 1, 7, 8, 9, 23
PARTY_ACCEPT = 2
TEXT = re.compile(r"\bescort\b|^help [^.]{1,60} escape|^protect |^accompany |protect (him|her|them) from harm", re.I)
# Flagged, but only an emote at an innkeeper (Hallow's End candy): nothing to wait for.
NOT = {8353, 8354, 8355, 8356, 8357, 8358, 8359, 8360}


def text_of(v):
    t = v.get(Q_OBJ_TEXT)
    if isinstance(t, dict):
        t = " ".join(str(t[k]) for k in sorted(t))
    return str(t or "").strip()


def trigger_of(v):
    t = v.get(Q_TRIGGER)
    return str(t.get(1) or "").strip() if isinstance(t, dict) else ""


def is_event(v):
    flags = v.get(Q_FLAGS)
    if isinstance(flags, (int, float)) and int(flags) & PARTY_ACCEPT:
        return True
    return bool(TEXT.search(text_of(v)) or TEXT.search(trigger_of(v)))


def main(root):
    quests = questie.load_forever(root)[0]
    ids = sorted(qid for qid, v in quests.items()
                 if qid not in NOT and not v.get(Q_CLASSES) and is_event(v))
    lines = ["-- Generated by tools/partyquests/build_events.py from QuestieDB (Forever data). Do not edit.",
             "-- Quest data (c) the Questie team and contributors, GPLv3.",
             "-- Quests whose NPC is busy for everyone else once one player starts them.",
             "local _, ns = ...",
             "ns.EVENT_QUESTS = {"]
    row = []
    for qid in ids:
        row.append("[%d]=true" % qid)
        if len(row) == 10:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    for out in OUTS:
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("%d event quests" % len(ids))


if __name__ == "__main__":
    main(sys.argv[1])
