#!/usr/bin/env python3
"""Writes Gulli-WritRunner/Data.lua from AllTheThings' WoW Forever data.

Usage: python3 tools/writrunner/build_data.py <AllTheThings checkout>

It reads `.contrib/.db/forever/expansion features/craftsman's writs.lua` as text (never runs it):
every Craftsman's Writ quest with its writ item, rank, profession, the item it asks for, the
customer and the spot, and the Sealed Writs with the writs they hold. AllTheThings is MIT.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "Gulli-WritRunner", "Data.lua")
SRC = os.path.join(".contrib", ".db", "forever", "expansion features", "craftsman's writs.lua")

# AllTheThings' map constants -> the client's uiMapID; K marks Kalimdor.
MAPS = {
    "ALTERAC_MOUNTAINS": (1416, ""), "ARATHI_HIGHLANDS": (1417, ""), "ASHENVALE": (1440, "K"),
    "AZSHARA": (1447, "K"), "BADLANDS": (1418, ""), "BLASTED_LANDS": (1419, ""),
    "BURNING_STEPPES": (1428, ""), "DEADWIND_PASS": (1430, ""), "DESOLACE": (1443, "K"),
    "DUSKWOOD": (1431, ""), "DUSTWALLOW_MARSH": (1445, "K"), "EASTERN_PLAGUELANDS": (1423, ""),
    "FELWOOD": (1448, "K"), "FERALAS": (1444, "K"), "HILLSBRAD_FOOTHILLS": (1424, ""),
    "MOONGLADE": (1450, "K"), "RIVERGLADES": (2548, "K"), "SEARING_GORGE": (1427, ""),
    "SILITHUS": (1451, "K"), "STONETALON_MOUNTAINS": (1442, "K"), "STRANGLETHORN_VALE": (1434, ""),
    "SWAMP_OF_SORROWS": (1435, ""), "TANARIS": (1446, "K"), "THE_HINTERLANDS": (1425, ""),
    "THOUSAND_NEEDLES": (1441, "K"), "UNGORO_CRATER": (1449, "K"), "WESTERN_PLAGUELANDS": (1422, ""),
    "WETLANDS": (1437, ""), "WINTERSPRING": (1452, "K"),
}
PROFS = {"ALCHEMY": "AL", "BLACKSMITHING": "BS", "ENGINEERING": "EN", "LEATHERWORKING": "LW", "TAILORING": "TA"}
TIERS = {"Journeyman": "J", "Expert": "E", "Artisan": "A"}
SEALED = {"262888": "J", "262889": "E", "262890": "A"}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(text):
    writs, npcs, prof = [], {}, None
    cur = None
    for line in text.split("\n"):
        m = re.search(r"prof\((\w+)", line)
        if m:
            prof = PROFS.get(m.group(1))
        m = re.search(r"q\((\d+), \{\s*-- Craftsman's Writ: (.*?) \[(\w+)\]", line)
        if m:
            cur = {"quest": int(m.group(1)), "name": m.group(2), "tier": TIERS[m.group(3)], "prof": prof}
            writs.append(cur)
            continue
        if cur is None:
            continue
        m = re.search(r"qs = (\d+),", line)
        if m:
            cur["writ"] = int(m.group(1))
        m = re.search(r"cr = (\d+),\s*-- (.*)$", line)
        if m:
            cur["npc"] = int(m.group(1))
            npcs[cur["npc"]] = re.sub(r"\s*<.*?>\s*$", "", m.group(2)).strip()
        m = re.search(r"coord = \{ ([\d.]+), ([\d.]+), MAP\.(\w+) \}", line)
        if m:
            cur["x"], cur["y"], cur["map"] = float(m.group(1)), float(m.group(2)), MAPS[m.group(3)][0]
        m = re.search(r'cost = \{ \{ "i", (\d+), (\d+) \} \}', line)
        if m:
            cur["item"], cur["count"] = int(m.group(1)), int(m.group(2))
        if "HORDE_ONLY" in line:
            cur["side"] = "H"
        elif "ALLIANCE_ONLY" in line:
            cur["side"] = "A"
    for w in writs:
        for k in ("writ", "item", "count", "prof"):
            if w.get(k) is None:
                raise SystemExit("writ %d has no %s" % (w["quest"], k))
    # what each Sealed Writ holds, as AllTheThings lists it (an empty list: all of that rank)
    sealed, at = {}, None
    for line in text.split("\n"):
        m = re.search(r"i\((26288[89]|262890)", line)
        if m:
            at = m.group(1)
            sealed[at] = []
            continue
        m = re.search(r"i\((\d+)\),\s*-- Craftsman's Writ", line)
        if m and at:
            sealed[at].append(int(m.group(1)))
    return writs, npcs, sealed


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    with open(os.path.join(sys.argv[1], SRC), encoding="utf-8") as f:
        writs, npcs, sealed = parse(f.read())
    writs.sort(key=lambda w: w["writ"])
    kalimdor = sorted({m for m, k in MAPS.values() if k == "K"})
    out = []
    out.append("-- Generated by tools/writrunner/build_data.py from AllTheThings' WoW Forever data (MIT):")
    out.append("-- the Craftsman's Writs and the Sealed Writs that hold them. Never edit it by hand.")
    out.append("local _, ns = ...")
    out.append("")
    out.append("-- writ item id -> { quest, rank (J, E, A), profession, item asked for, count, side (A, H or nil),")
    out.append("--                   customer npc, uiMapID, x, y } (no customer: nil for the last four)")
    out.append("ns.WRITS = {")
    for w in writs:
        side = lua_str(w["side"]) if w.get("side") else "nil"
        place = "nil, nil, nil, nil"
        if w.get("npc"):
            place = "%d, %d, %.1f, %.1f" % (w["npc"], w["map"], w["x"], w["y"])
        out.append("    [%d] = { %d, %s, %s, %d, %d, %s, %s }, -- %s" % (
            w["writ"], w["quest"], lua_str(w["tier"]), lua_str(w["prof"]), w["item"], w["count"], side, place,
            w["name"]))
    out.append("}")
    out.append("")
    out.append("-- customer npc -> English name (the client's own name wins when it has the unit)")
    out.append("ns.NPCS = {")
    for npc in sorted(npcs):
        out.append("    [%d] = %s," % (npc, lua_str(npcs[npc])))
    out.append("}")
    out.append("")
    out.append("-- Sealed Writ item id -> its rank; it holds a random writ of that rank")
    out.append("ns.SEALED = {")
    for sid, tier in sorted(SEALED.items()):
        out.append("    [%s] = %s, -- %d writs listed" % (sid, lua_str(tier), len(sealed.get(sid, []))))
    out.append("}")
    out.append("")
    out.append("ns.KALIMDOR = { " + ", ".join(str(m) for m in kalimdor) + " }")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("%d writs, %d customers, %d without one" % (
        len(writs), len(npcs), sum(1 for w in writs if not w.get("npc"))))


if __name__ == "__main__":
    main()
