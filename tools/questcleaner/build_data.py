"""Builds Gulli-QuestCleaner/Data.lua from the QuestieDB Forever data.

    python3 tools/questcleaner/build_data.py <questiedb-checkout>

The table holds only what the cleaner needs: which quests ask for each quest item,
who can still take those quests, and which quest items stay useful after their quest.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import luadata  # noqa: E402

ITEM_CLASS_QUEST = 12
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Gulli-QuestCleaner", "Data.lua")

# questKeys and itemKeys of QuestieDB (src/meta/*Meta.lua).
Q_STARTED_BY, Q_LEVEL, Q_RACES, Q_CLASSES = 2, 5, 6, 7
Q_OBJECTIVES, Q_SOURCE_ITEM, Q_PRE_GROUP, Q_PRE_SINGLE = 10, 11, 12, 13
Q_EXCLUSIVE, Q_SOURCE_ITEMS, Q_NEXT, Q_BREADCRUMB_FOR, Q_MAX_LEVEL = 16, 21, 22, 27, 32
I_START_QUEST, I_REWARD_OF, I_CLASS = 5, 6, 12


def seq(t):
    return [t[k] for k in sorted(t)] if isinstance(t, dict) else []


def lua_list(values):
    return "{" + ",".join(str(v) for v in values) + "}"


def main(root):
    quests = luadata.load(os.path.join(root, "data/Forever/foreverQuestDB.lua"), "questData")
    items = luadata.load(os.path.join(root, "data/Forever/foreverItemDB.lua"), "itemData")

    def is_quest_item(i):
        return items.get(i, {}).get(I_CLASS) == ITEM_CLASS_QUEST

    need = {}
    for qid, q in quests.items():
        wanted = [o[1] for o in seq((q.get(Q_OBJECTIVES) or {}).get(3) or {}) if o.get(1)]
        wanted += seq(q.get(Q_SOURCE_ITEMS) or {})
        for i in wanted:
            if is_quest_item(i):
                need.setdefault(i, set()).add(qid)

    # Quest-class rewards that no quest asks for and that start nothing: keys, tools,
    # Juju, arcanums, summoning items. They stay useful after the quest.
    keep = sorted(i for i, it in items.items()
                  if it.get(I_CLASS) == ITEM_CLASS_QUEST and it.get(I_REWARD_OF)
                  and i not in need and not it.get(I_START_QUEST))

    used = sorted({qid for qs in need.values() for qid in qs})
    lines = []
    lines.append("-- Generated by tools/questcleaner/build_data.py from QuestieDB (Forever data). Do not edit.")
    lines.append("-- Quest and item data (c) the Questie team and contributors, GPLv3.")
    lines.append("local _, ns = ...")
    lines.append("local D = {}")
    lines.append("ns.Data = D")
    lines.append("-- Quest item -> quests that ask for it.")
    lines.append("D.need = {")
    for i in sorted(need):
        lines.append("[%d]=%s," % (i, lua_list(sorted(need[i]))))
    lines.append("}")
    lines.append("-- Quest -> { level, race mask, class mask, max level, quests that close it }.")
    lines.append("D.quest = {")
    for qid in used:
        q = quests[qid]
        closed = set(seq(q.get(Q_EXCLUSIVE) or {}))
        for k in (Q_NEXT, Q_BREADCRUMB_FOR):
            if q.get(k):
                closed.add(q[k])
        closed.discard(qid)
        row = [q.get(Q_LEVEL) or 0, q.get(Q_RACES) or 0, q.get(Q_CLASSES) or 0, q.get(Q_MAX_LEVEL) or 0]
        lines.append("[%d]={%s%s}," % (qid, ",".join(str(v) for v in row),
                                       ("," + lua_list(sorted(closed))) if closed else ""))
    lines.append("}")

    def id_set(name, comment, ids):
        lines.append("-- " + comment)
        out, row = [], []
        for i in sorted(ids):
            row.append("[%d]=1" % i)
            if len(row) == 12:
                out.append(",".join(row) + ",")
                row = []
        if row:
            out.append(",".join(row) + ",")
        lines.append("D.%s = {" % name)
        lines.extend(out)
        lines.append("}")

    id_set("keep", "Quest items that stay useful after their quest.", keep)
    id_set("itemStart", "Quests started by an item.",
           [qid for qid, q in quests.items() if seq((q.get(Q_STARTED_BY) or {}).get(3) or {})])
    id_set("chain", "Quests that need an earlier quest.",
           [qid for qid, q in quests.items() if q.get(Q_PRE_GROUP) or q.get(Q_PRE_SINGLE)])
    id_set("class", "Class quests.", [qid for qid, q in quests.items() if q.get(Q_CLASSES)])

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("items %d, quests %d, keep %d, %d bytes" % (len(need), len(used), len(keep), os.path.getsize(OUT)))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
