"""Builds Gulli-DungeonPrep/JournalData.lua from a Wowhead snapshot of the WoW Forever dungeons.

    python3 tools/dungeonprep/build_journal.py [tools/dungeonprep/wowhead-dungeons.json]

The snapshot is collected from Wowhead's WoW Forever pages on a player's computer (Wowhead
refuses scripted reads from servers) and kept next to this file, so the generator runs anywhere.
Its shape:

    {"dungeons": {"DM": {"bosses": [{"id", "name", "tag", "minLevel", "maxLevel", "displayId",
        "abilities": [[spell id, name]], "drops": [{"id", "quality", "class", "pct", "count",
        "outof"}]}], "rares": [...same...]}}}

Bosses keep the snapshot's order (the order Wowhead lists them in), with rares after them.
The snapshot is untrusted text: it is only read as JSON, never run. A drop is kept when it is
uncommon or better, or a quest item, and its chance comes from enough kills.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "wowhead-dungeons.json")
OUT = os.path.join(HERE, "..", "..", "Gulli-DungeonPrep", "JournalData.lua")
sys.path.insert(0, HERE)
from build_data import DUNGEONS  # noqa: E402

QUEST_CLASS = 12
MIN_QUALITY = 2       # uncommon
MIN_OUTOF = 10        # kills behind a chance
MIN_PCT = 0.5         # rarer drops are noise
MAX_DROPS = 30        # per boss, best first
MAX_SPELLS = 8


def lua_str(s):
    s = str(s or "")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def pct_of(d):
    pct = d.get("pct")
    if pct is None and d.get("outof"):
        pct = 100.0 * (d.get("count") or 0) / d["outof"]
    return float(pct or 0)


def keep_drop(d):
    if d.get("outof") is not None and d["outof"] < MIN_OUTOF:
        return False
    if pct_of(d) < MIN_PCT:
        return False
    return (d.get("quality") or 0) >= MIN_QUALITY or d.get("class") == QUEST_CLASS


def as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


def boss_row(b, rare):
    drops = sorted((d for d in b.get("drops") or [] if as_int(d.get("id")) > 0 and keep_drop(d)),
                   key=lambda d: (-(d.get("quality") or 0), -pct_of(d), as_int(d["id"])))[:MAX_DROPS]
    loot = ",".join("{%d,%d,%s}" % (as_int(d["id"]), as_int(d.get("quality")),
                                    ("%.1f" % pct_of(d)).rstrip("0").rstrip("."))
                    for d in drops)
    spells = [as_int(a[0] if isinstance(a, list) else a) for a in b.get("abilities") or []]
    spells = ",".join(str(s) for s in [s for s in spells if s > 0][:MAX_SPELLS])
    return "{%d,%s,%s,%d,%d,%d,%d,{%s},{%s}}" % (
        as_int(b["id"]), lua_str(b.get("name")), lua_str(b.get("tag")), as_int(b.get("minLevel")),
        as_int(b.get("maxLevel")), as_int(b.get("displayId")), 1 if rare else 0, spells, loot)


def build(snapshot):
    known = [d[0] for d in DUNGEONS]
    data = snapshot.get("dungeons") or {}
    lines = [
        "-- Generated by tools/dungeonprep/build_journal.py from a Wowhead snapshot. Do not edit.",
        "local _, ns = ...",
        "local D = ns.Data",
        "-- D.boss[dungeon] = { { npc, name, tag, min level, max level, display id, rare (1),",
        "--   { ability spell ids }, { { item, quality, drop chance in percent } } } }, bosses in order.",
        "D.boss = {",
    ]
    missing = []
    for key in known:
        d = data.get(key)
        if not d:
            missing.append(key)
            continue
        rows = [boss_row(b, False) for b in d.get("bosses") or [] if as_int(b.get("id")) > 0]
        rows += [boss_row(b, True) for b in d.get("rares") or [] if as_int(b.get("id")) > 0]
        if not rows:
            missing.append(key)
            continue
        lines.append("%s = {" % key)
        lines.extend(r + "," for r in rows)
        lines.append("},")
    lines.append("}")
    unknown = sorted(set(data) - set(known))
    return "\n".join(lines) + "\n", missing, unknown


def main(src):
    with open(src, encoding="utf-8") as f:
        snapshot = json.load(f)
    text, missing, unknown = build(snapshot)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    if missing:
        print("no bosses for: " + ", ".join(missing))
    if unknown:
        print("not a DungeonPrep dungeon, skipped: " + ", ".join(unknown))
    print("wrote " + os.path.relpath(OUT))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else SRC)
