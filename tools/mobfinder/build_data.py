"""Builds Gulli-MobFinder/Data.lua from the QuestieDB Forever data.

    python3 tools/mobfinder/build_data.py <questiedb-checkout>

Lists the rare mobs (rank 4 rare, rank 2 rare elite) by the area ids where they spawn, with
their npc id, English name and level range. The addon matches them by the npc id in the
nameplate's GUID, so it works in every client language. QuestieDB is GPLv3.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "questcleaner"))
import questie  # noqa: E402

OUT = os.path.join(HERE, "..", "..", "Gulli-MobFinder", "Data.lua")

# npcKeys of QuestieDB (src/meta/npcMeta.lua).
N_NAME, N_MIN, N_MAX, N_RANK, N_SPAWNS, N_ZONE = 1, 4, 5, 6, 7, 9
RARE, RARE_ELITE = 4, 2


def lua_str(s):
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(root):
    # With the Forever corrections: the rares of Forever's own zones live there.
    _, npcs, _, _ = questie.load_forever(root)
    by_area = {}
    for nid, n in npcs.items():
        if not isinstance(n, dict) or n.get(N_RANK) not in (RARE, RARE_ELITE):
            continue
        areas = set()
        if isinstance(n.get(N_SPAWNS), dict):
            areas.update(n[N_SPAWNS].keys())
        if not areas and n.get(N_ZONE):
            areas.add(n[N_ZONE])
        for a in areas:
            by_area.setdefault(a, []).append(
                (nid, n.get(N_NAME) or "", n.get(N_MIN) or 0, n.get(N_MAX) or 0, 1 if n[N_RANK] == RARE_ELITE else 0))
    lines = [
        "-- Generated by tools/mobfinder/build_data.py from the QuestieDB Forever data (GPLv3).",
        "-- Do not edit by hand. Area id -> { { npc id, English name, min level, max level, elite } }.",
        "local _, ns = ...",
        "ns.RARES = {",
    ]
    count = 0
    for area in sorted(by_area):
        rows = sorted(by_area[area], key=lambda r: (r[2], r[1]))
        count += len(rows)
        lines.append("    [%d] = { %s }," % (area, ", ".join(
            "{ %d, %s, %d, %d, %d }" % (r[0], lua_str(r[1]), r[2], r[3], r[4]) for r in rows)))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d rares in %d areas -> %s" % (count, len(by_area), OUT))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
