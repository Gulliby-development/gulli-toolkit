ns.MUTE_KINDS = { "hooves", "mechano", "airships", "weather", "fizzle" }

local muted = {} -- kind -> true while its sounds are muted

local function setKind(kind, on)
    if (muted[kind] == true) == on then return end
    local fn = on and MuteSoundFile or UnmuteSoundFile
    if not fn then return end
    for _, id in ipairs(ns.MUTE_SOUNDS[kind] or {}) do pcall(fn, id) end
    muted[kind] = on or nil
end

local function apply(get)
    for _, kind in ipairs(ns.MUTE_KINDS) do setKind(kind, get(kind) == true) end
end

function ns.MutedKinds() return muted end

local panel = { { kind = "head", label = L.TWP_MUTE_HEAD } }
for _, kind in ipairs(ns.MUTE_KINDS) do
    panel[#panel + 1] = { kind = "check", key = kind, label = L["TWP_MUTE_" .. kind:upper()] }
end

ns.AddTweak({
    key = KEY, group = "ui", icon = "Interface\\Icons\\INV_Misc_Drum_01", star = true,
    defaults = { hooves = true, mechano = true, airships = true, weather = false, fizzle = true },
    panel = panel,
    enable = apply,
    disable = function()
        for _, kind in ipairs(ns.MUTE_KINDS) do setKind(kind, false) end
    end,
    changed = function(_, _, get) apply(get) end,
})
